#!/usr/bin/env python3
"""S12 Task 6 (design D11): write app/src/knight_root.h, Gaius's root-motion tables.

  python3 -I tools/re/s12/knight_root.py [glb] [knight_root.h]

The twin of tools/re/s11/quadratus_root.py. The glb defaults to $SOTC_LIB/models/shadow/
characters/colossus_03_knight/_cmn/colossus_03_knight.glb (it must carry his S12 bake:
`make bake-knight` into the branch's view); the `.anb` files are read from $SOTC_GAME_ROOT
(both read-only). The header names the glb's sha256.

What the header carries (all measured; recon: .superpowers/sdd/2026-10-23-s12-recon/sword/
findings.md "Root motion"):
  - root: every `knight_a_*` clip with a root series, per-frame root (x, z) relative to
    frame 0 in the clip-start (glb model) frame, read with parse2.decode_root through
    s8/root_z.anb_root. **x is negated** (glb x = -anb x, as for Quadratus). The bake zeroes
    root x/z in the glb (GlbWriter.cs) and keeps y in the glb's root track, which this script
    checks against the `.anb`; y is therefore not tabled (never add it twice). Clips without
    a series (14, incl. `boot`) are listed as such: they must never play raw.
  - turn yaw / heading: the heading of the hip line (Bone_MOMO_R -> Bone_MOMO_L; for a biped
    the body faces 90 deg from it) per frame, relative to frame 0 and unwrapped, for the
    three turn clips; app convention, + = toward the model's +x = a left turn. The last
    value is the clip's turn yaw.
The loop set is authored (sword.json root.loops_proposed). Stdlib only.
"""

import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(HERE, "..", "s8"))
sys.path.insert(0, os.path.join(HERE, "..", "s11"))
import root_z  # noqa: E402  (anb_root)
from quadratus_root import Glb, f  # noqa: E402  (the glb FK reader, the float literal)

GLB_REL = "models/shadow/characters/colossus_03_knight/_cmn/colossus_03_knight.glb"
PREFIX = "knight_a_"
# Authored (sword.json root.loops_proposed): the root-carrying clips that wrap.
LOOPS = {"back", "search", "stand", "walk"}
TURNS = ["turn_l", "turn_r", "turn_back"]


def heading_deg(glb, clip, frame):
    r = glb.world(clip, glb.index["Bone_MOMO_R"], frame)[0]
    l = glb.world(clip, glb.index["Bone_MOMO_L"], frame)[0]
    return math.degrees(math.atan2(l[0] - r[0], l[2] - r[2]))


def measure(glb_path, game=None):
    try:
        glb = Glb(glb_path)
    except SystemExit:   # Glb's no-animations refusal names Quadratus's bake
        raise SystemExit("%s has no animations: not Gaius's S12 bake (run `make bake-knight` "
                         "into SOTC_LIB)" % glb_path)
    names = sorted(n[len(PREFIX):] for n in glb.anims if n.startswith(PREFIX))
    root, rootless = {}, []
    for c in names:
        clip, frames, last_t = glb.clip(PREFIX + c)
        try:
            n, fps, v = root_z.anb_root(PREFIX + c, game)
        except ValueError:
            rootless.append(c)
            continue
        if n < 2:
            raise ValueError("%s: a %d-frame root series cannot be sampled" % (c, n))
        if n != frames or abs((n - 1) / fps - last_t) > 1e-3:
            raise ValueError("%s: anb %d frames @ %.4f vs glb %d frames, %.4f s" % (c, n, fps, frames, last_t))
        gy = clip.get((glb.index["Bone_root"], "translation"))
        if gy and max(abs(a[1] - b[1]) for a, b in zip(gy, v)) > 1e-3:
            raise ValueError("%s: glb root y differs from the anb's" % c)
        x0, _, z0 = v[0]
        root[c] = {"fps": fps, "loop": c in LOOPS,
                   "xz": [(-(x - x0), z - z0) for x, _, z in v]}   # glb x = -anb x
    heading = {}
    for c in TURNS:
        clip, frames, last_t = glb.clip(PREFIX + c)
        cum, prev = [0.0], heading_deg(glb, clip, 0)
        for k in range(1, frames):
            h = heading_deg(glb, clip, k)
            cum.append(cum[-1] + math.remainder(h - prev, 360.0))
            prev = h
        heading[c] = {"fps": (frames - 1) / last_t, "deg": cum}
    return {"root": root, "rootless": rootless, "heading": heading,
            "glb": os.path.basename(glb_path), "sha256": glb.sha256}


def render(d):
    out = []
    w = out.append
    w("#pragma once")
    w("")
    w("// GENERATED by tools/re/s12/knight_root.py from Gaius's baked glb and his `.anb` root")
    w("// series — do not edit; re-run the generator. glb: %s (the S12 bake, `make" % d["glb"])
    w("// bake-knight`), sha256 %s." % d["sha256"])
    w("// All values measured (sword recon, S12); the loop flags are authored (sword.json).")
    w("//")
    w("//   kRoots — every knight_a_* clip with a root series: per-frame root (x, z), metres,")
    w("//     relative to frame 0, in the clip-start frame (glb model frame: +z front, +x the")
    w("//     model's left). x is the NEGATED `.anb` x (glb x = -anb x); z is raw. y is NOT here:")
    w("//     it is in the glb's own root track (never add it twice).")
    w("//     frame = time * fps; the clip's length is (frames - 1) / fps.")
    w("//   kNoRoot — the clips with no root series: they move nothing and must never play raw")
    w("//     (his feet would sit ~12.7 m under the ground).")
    w("//   kTurnHeading — the hip line's heading per frame, relative to frame 0, unwrapped (deg);")
    w("//     + = toward the model's +x = a left turn (app yaw). Its last value is the turn's yaw.")
    w("")
    w("namespace knight_root {")
    w("")
    w("struct RootSeries {")
    w("    const char* clip;")
    w("    float fps;")
    w("    int frames;")
    w("    bool loop;")
    w("    const float (*xz)[2];")
    w("};")
    w("")
    for c, r in d["root"].items():
        w("inline constexpr float kXZ_%s[][2] = {%s};" % (
            c, ", ".join("{%s, %s}" % tuple(f(v) for v in p) for p in r["xz"])))
    w("")
    w("inline constexpr RootSeries kRoots[] = {")
    for c, r in d["root"].items():
        w('    {"%s%s", %s, %d, %s, kXZ_%s},' % (PREFIX, c, f(r["fps"]), len(r["xz"]),
                                              "true" if r["loop"] else "false", c))
    w("};")
    w("")
    w("inline constexpr const char* kNoRoot[] = {%s};" % ", ".join(
        '"%s%s"' % (PREFIX, c) for c in sorted(d["rootless"])))
    w("")
    w("struct TurnHeading {")
    w("    const char* clip;")
    w("    float fps;")
    w("    int frames;")
    w("    const float* deg;")
    w("};")
    w("")
    for c, h in d["heading"].items():
        w("inline constexpr float kHeading_%s[] = {%s};" % (
            c, ", ".join(repr(round(v, 2)) + "f" for v in h["deg"])))
    w("")
    w("inline constexpr TurnHeading kTurnHeading[] = {")
    for c, h in d["heading"].items():
        w('    {"%s%s", %s, %d, kHeading_%s},' % (PREFIX, c, f(h["fps"]), len(h["deg"]), c))
    w("};")
    w("")
    w("}  // namespace knight_root")
    return "\n".join(out) + "\n"


def main(argv):
    lib = os.environ.get("SOTC_LIB") or os.path.join(REPO, "out", "library")
    src = argv[1] if len(argv) > 1 else os.path.join(lib, GLB_REL)
    dst = argv[2] if len(argv) > 2 else os.path.join(REPO, "app", "src", "knight_root.h")
    if not os.path.isfile(src):
        raise SystemExit("%s: no such glb (export SOTC_LIB, or run `make bake-knight`)" % src)
    d = measure(src)
    with open(dst, "w") as fh:
        fh.write(render(d))
    for c, r in d["root"].items():
        x, z = r["xz"][-1]
        print("root %-28s %3d @ %7.4f %s  end (%+8.3f, %+8.3f)" % (
            c, len(r["xz"]), r["fps"], "loop" if r["loop"] else "    ", x, z))
    print("no root (%d): %s" % (len(d["rootless"]), ", ".join(sorted(d["rootless"]))))
    for c, h in d["heading"].items():
        deg = h["deg"]
        print("heading %-12s %3d @ %7.4f  mid %+7.2f  end %+7.2f" % (
            c, len(deg), h["fps"], deg[(len(deg) - 1) // 2], deg[-1]))
    print("wrote %s (glb sha256 %s)" % (dst, d["sha256"]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
