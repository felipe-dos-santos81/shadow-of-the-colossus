#!/usr/bin/env python3
"""S13 Task 11: write app/src/kirin_root.h, Phaedra's root-motion tables.

  python3 -I tools/re/s13/kirin_root.py [glb] [kirin_root.h]

The twin of tools/re/s12/knight_root.py. The glb defaults to $SOTC_LIB/models/shadow/characters/
colossus_04_kirin/_cmn/c04_kirin.glb (it must carry her S13 bake: `make bake-kirin` into the
branch's view); the `.anb` files are read from $SOTC_GAME_ROOT (both read-only). The header names the
glb's sha256.

What the header carries (all measured; recon: .superpowers/sdd/2026-10-23-s13-recon/kirin/findings.md
section 2):
  - root: every `kirin_a_*` clip with a usable root series, per-frame root (x, z) relative to
    frame 0 in the clip-start (glb model) frame, read with parse2.decode_root through
    s8/root_z.anb_root. **x is negated** (glb x = -anb x, as for Quadratus and Gaius). The bake
    zeroes root x/z in the glb (GlbWriter.cs) and keeps y in the glb's root track, which this script
    checks against the `.anb`; y is therefore not tabled (never add it twice). The 25 clips
    without a series are listed (kNoRoot): they sink 9.86 m if played raw. `boot` has a series but
    its absolute y (58.29 m: she comes down from the hill) is unusable, so it is listed apart
    (kUnusable), not tabled.
  - turn heading: the body-axis heading (rear hips' mid Bone_MOMO_* -> shoulders' mid Bone_JOWAN_*,
    quadratus_root.heading_deg) per frame, relative to frame 0 and unwrapped, for the four turn
    clips; app convention, + = toward the model's +x = a left turn. The last value is the turn yaw.
  - kDeathRoot: the death drop, root y 9.86 -> 2.44 m (measured: `death` has no root series; with
    root 0 its lowest vertex goes -9.90 -> -2.44, so this authored root keeps her on the ground).
The loop set is authored. Stdlib only.
"""

import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(HERE, "..", "s8"))
sys.path.insert(0, os.path.join(HERE, "..", "s11"))
import root_z  # noqa: E402  (anb_root)
from quadratus_root import Glb, f, heading_deg  # noqa: E402  (the glb FK reader, the float literal)

GLB_REL = "models/shadow/characters/colossus_04_kirin/_cmn/c04_kirin.glb"
PREFIX = "kirin_a_"
# Authored: the root-carrying clips that wrap (idle, the walks' loop bodies, the crouch-peek holds).
LOOPS = {"seach", "stand", "walk", "walk_angry_loop", "walk_back", "watch2_loop", "watch_loop"}
UNUSABLE = {"boot": "absolute root y 58.29 m: she comes down from the hill"}
TURNS = ["turn_l", "turn_r", "walk_turn_l", "walk_turn_r"]


def measure(glb_path, game=None):
    try:
        glb = Glb(glb_path)
    except SystemExit:   # Glb's no-animations refusal names Quadratus's bake
        raise SystemExit("%s has no animations: not Phaedra's S13 bake (run `make bake-kirin` "
                         "into SOTC_LIB)" % glb_path)
    names = sorted(n[len(PREFIX):] for n in glb.anims if n.startswith(PREFIX))
    root, rootless = {}, []
    for c in names:
        clip, frames, last_t = glb.clip(PREFIX + c)
        try:
            n, fps, v = root_z.anb_root(PREFIX + c, game)
        except ValueError:
            rootless.append(c)
            continue
        if n < 2:
            raise ValueError("%s: a %d-frame root series cannot be sampled" % (c, n))
        if n != frames or abs((n - 1) / fps - last_t) > 1e-3:
            raise ValueError("%s: anb %d frames @ %.4f vs glb %d frames, %.4f s" % (c, n, fps, frames, last_t))
        gy = clip.get((glb.index["Bone_root"], "translation"))
        if gy and max(abs(a[1] - b[1]) for a, b in zip(gy, v)) > 1e-3:
            raise ValueError("%s: glb root y differs from the anb's" % c)
        if c in UNUSABLE:
            continue
        x0, _, z0 = v[0]
        root[c] = {"fps": fps, "loop": c in LOOPS,
                   "xz": [(-(x - x0), z - z0) for x, _, z in v]}   # glb x = -anb x
    heading = {}
    for c in TURNS:
        clip, frames, last_t = glb.clip(PREFIX + c)
        cum, prev = [0.0], heading_deg(glb, clip, 0)
        for k in range(1, frames):
            h = heading_deg(glb, clip, k)
            cum.append(cum[-1] + math.remainder(h - prev, 360.0))
            prev = h
        heading[c] = {"fps": (frames - 1) / last_t, "deg": cum}
    return {"root": root, "rootless": rootless, "heading": heading,
            "glb": os.path.basename(glb_path), "sha256": glb.sha256}


def render(d):
    out = []
    w = out.append
    w("#pragma once")
    w("")
    w("// GENERATED by tools/re/s13/kirin_root.py from Phaedra's baked glb and her `.anb` root")
    w("// series — do not edit; re-run the generator. glb: %s (the S13 bake, `make" % d["glb"])
    w("// bake-kirin`), sha256 %s." % d["sha256"])
    w("// All values measured (kirin recon, S13); the loop flags and kDeathRoot's use are authored.")
    w("//")
    w("//   kRoots — every kirin_a_* clip with a usable root series: per-frame root (x, z), metres,")
    w("//     relative to frame 0, in the clip-start frame (glb model frame: +z front, +x the")
    w("//     model's left). x is the NEGATED `.anb` x (glb x = -anb x); z is raw. y is NOT here:")
    w("//     it is in the glb's own root track (never add it twice).")
    w("//     frame = time * fps; the clip's length is (frames - 1) / fps.")
    w("//   kNoRoot — the clips with no root series: they move nothing and must never play raw")
    w("//     (she would sit 9.86 m under the ground).")
    w("//   kUnusable — a root series exists but is not usable (%s)." % "; ".join(
        "%s: %s" % (PREFIX + k, v) for k, v in UNUSABLE.items()))
    w("//   kTurnHeading — the body axis' heading per frame, relative to frame 0, unwrapped (deg);")
    w("//     + = toward the model's +x = a left turn (app yaw). Its last value is the turn's yaw.")
    w("//   kDeathRoot — `kirin_a_death` has no root series: its root y falls from kFrom to kTo.")
    w("")
    w("namespace kirin_root {")
    w("")
    w("struct RootSeries {")
    w("    const char* clip;")
    w("    float fps;")
    w("    int frames;")
    w("    bool loop;")
    w("    const float (*xz)[2];")
    w("};")
    w("")
    for c, r in d["root"].items():
        w("inline constexpr float kXZ_%s[][2] = {%s};" % (
            c, ", ".join("{%s, %s}" % tuple(f(v) for v in p) for p in r["xz"])))
    w("")
    w("inline constexpr RootSeries kRoots[] = {")
    for c, r in d["root"].items():
        w('    {"%s%s", %s, %d, %s, kXZ_%s},' % (PREFIX, c, f(r["fps"]), len(r["xz"]),
                                              "true" if r["loop"] else "false", c))
    w("};")
    w("")
    w("inline constexpr const char* kNoRoot[] = {%s};" % ", ".join(
        '"%s%s"' % (PREFIX, c) for c in sorted(d["rootless"])))
    w("inline constexpr const char* kUnusable[] = {%s};" % ", ".join(
        '"%s%s"' % (PREFIX, c) for c in sorted(UNUSABLE)))
    w("")
    w("struct DeathRoot {")
    w("    float kFrom;  // measured: the standing root y")
    w("    float kTo;    // measured: the lowest vertex at the end of the fall, so the dead body rests on the ground")
    w("};")
    w("inline constexpr DeathRoot kDeathRoot{9.86f, 2.44f};")
    w("")
    w("struct TurnHeading {")
    w("    const char* clip;")
    w("    float fps;")
    w("    int frames;")
    w("    const float* deg;")
    w("};")
    w("")
    for c, h in d["heading"].items():
        w("inline constexpr float kHeading_%s[] = {%s};" % (
            c, ", ".join(repr(round(v, 2)) + "f" for v in h["deg"])))
    w("")
    w("inline constexpr TurnHeading kTurnHeading[] = {")
    for c, h in d["heading"].items():
        w('    {"%s%s", %s, %d, kHeading_%s},' % (PREFIX, c, f(h["fps"]), len(h["deg"]), c))
    w("};")
    w("")
    w("}  // namespace kirin_root")
    return "\n".join(out) + "\n"


def main(argv):
    lib = os.environ.get("SOTC_LIB") or os.path.join(REPO, "out", "library")
    src = argv[1] if len(argv) > 1 else os.path.join(lib, GLB_REL)
    dst = argv[2] if len(argv) > 2 else os.path.join(REPO, "app", "src", "kirin_root.h")
    if not os.path.isfile(src):
        raise SystemExit("%s: no such glb (export SOTC_LIB, or run `make bake-kirin`)" % src)
    d = measure(src)
    with open(dst, "w") as fh:
        fh.write(render(d))
    for c, r in d["root"].items():
        x, z = r["xz"][-1]
        print("root %-28s %3d @ %7.4f %s  end (%+8.3f, %+8.3f)" % (
            c, len(r["xz"]), r["fps"], "loop" if r["loop"] else "    ", x, z))
    print("no root (%d): %s" % (len(d["rootless"]), ", ".join(sorted(d["rootless"]))))
    for c, h in d["heading"].items():
        deg = h["deg"]
        print("heading %-12s %3d @ %7.4f  mid %+7.2f  end %+7.2f" % (
            c, len(deg), h["fps"], deg[(len(deg) - 1) // 2], deg[-1]))
    print("wrote %s (glb sha256 %s)" % (dst, d["sha256"]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
