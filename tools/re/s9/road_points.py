#!/usr/bin/env python3
"""S9 Task 7: write app/src/road_points.h from tools/re/s9/placements.json.

  python3 -I tools/re/s9/road_points.py [placements.json] [road_points.h]

Transcribes the two arena doors (`door_corridor`, `door_arena`: boxes and arrival
spawns), Valus's target (`valus`), the sword tip (`sword.tip`), the selftest/e2e
probes (`probes`), the sword textures (`textures`, library-relative PNGs) and their
atlas grid (`textures.frame`) verbatim, so the header is reproducible from the
gate's output (the S8 `ride_points.py` pattern). Stdlib only.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", ".."))


def f(v):
    return repr(float(v)) + "f"


def fl(vs):
    return ", ".join(f(v) for v in vs)


def render(d):
    dc, da, va = d["door_corridor"], d["door_arena"], d["valus"]
    sw, tx, pr = d["sword"], d["textures"], d["probes"]
    out = []
    w = out.append
    w("#pragma once")
    w("")
    w("// GENERATED by tools/re/s9/road_points.py from tools/re/s9/placements.json — do not edit;")
    w("// re-run the generator. Transcribed verbatim (the S8 ride_points.h pattern).")
    w("//")
    w("// Provenance (placements.json keys):")
    w("//   `door_corridor` (source: %s) — the box: %s;" % (dc["source"], dc["box_source"]))
    w("//     the arrival: %s;" % dc["arrive_source"])
    w("//   `door_arena` (source: %s) — the box where the arena's unlayered map reaches" % da["source"])
    w("//     from its spawn; the arrival on the road's corridor floor, below the cliff;")
    w("//   `valus` (source: %s) — the encounter manifest's entity feet, the chest lift" % va["source"])
    w("//     (Bone_MUNE);")
    w("//   `sword.tip` (source: %s) — in %s's frame;" % (sw["source"], sw["bone"]))
    w("//   `probes` (source: %s) — world points on the road (y = ground);" % pr["source"])
    w("//   `textures` — the four sword PNGs, library-relative ([0] lines, [1] overlay,")
    w("//     [2] flare, [3] hit: sword_fx.h's order); `textures.frame` the atlas grid.")
    w("")
    w("#include <array>")
    w("#include <string>")
    w("")
    w('#include "ride_points.h"')
    w("")
    w("namespace road_points {")
    w("")
    w("// The arena doors (design D3; ride_points::Door reused): `kDoorCorridor` is on the")
    w("// road (world frame) and arrives at the arena spawn; `kDoorArena` is in the arena")
    w("// (world frame) and arrives on the road.")
    for name, door, arrive in (("kDoorCorridor", dc, dc["arrive_arena"]),
                               ("kDoorArena", da, da["arrive_road"])):
        w("inline constexpr ride_points::Door %s{{%s}, {%s}, {%s}, %s};" % (
            name, fl(door["min"]), fl(door["max"]), fl(arrive["p"]), f(arrive["yaw_deg"])))
    w("")
    w("// Valus's target (D5): his feet in the world and the chest's lift above them.")
    w("inline constexpr float kValusFeet[3]{%s};" % fl(va["feet"]))
    w("inline constexpr float kValusChestLift = %s;" % f(va["chest_lift"]))
    w("")
    w("// The beam's origin in %s's frame (%s)." % (sw["bone"], sw["source"]))
    w("inline constexpr float kSwordTip[3]{%s};" % fl(sw["tip"]))
    w("")
    sun, agro = pr["sunlit"], pr["agro_stairs"]
    w("// The probes (world x, y = ground, z): the sunlit standpoint and the yaw that faces")
    w("// away from Valus, the shaded point, the stairs' foot, the entrance top, Agro's")
    w("// stand by the stairs (yaw toward Valus's chest), and the e2e route's x/z legs.")
    w("inline constexpr float kProbeSunlit[3]{%s};" % fl(sun["p"]))
    w("inline constexpr float kProbeSunlitYawAwayDeg = %s;" % f(sun["yaw_away_deg"]))
    w("inline constexpr float kProbeShade[3]{%s};" % fl(pr["shade"]["p"]))
    w("inline constexpr float kStairsFoot[3]{%s};" % fl(pr["stairs_foot"]))
    w("inline constexpr float kEntranceTop[3]{%s};" % fl(pr["entrance_top"]))
    w("inline constexpr float kAgroStairs[3]{%s};" % fl(agro["p"]))
    w("inline constexpr float kAgroStairsYawDeg = %s;" % f(agro["yaw_deg"]))
    w("inline constexpr float kE2eRoute[][2]{%s};" % ", ".join(
        "{%s}" % fl(p) for p in pr["e2e_route"]))
    w("inline constexpr int kE2eRouteCount = %d;" % len(pr["e2e_route"]))
    w("")
    w("// The sword's four textures (library-relative PNGs) and their atlas grid {cols, rows}.")
    w("inline const std::array<std::string, 4> kSwordTextures{")
    for key in ("lines", "overlay", "flare", "hit"):
        w('    "%s",  // %s' % (tx[key], tx["emitters"][key]))
    w("};")
    w("inline constexpr int kSwordAtlasGrid[2]{%d, %d};" % tuple(tx["frame"]))
    w("")
    w("}  // namespace road_points")
    return "\n".join(out) + "\n"


def main(argv):
    src = argv[1] if len(argv) > 1 else os.path.join(HERE, "placements.json")
    dst = argv[2] if len(argv) > 2 else os.path.join(REPO, "app", "src", "road_points.h")
    with open(src) as fh:
        d = json.load(fh)
    text = render(d)
    with open(dst, "w") as fh:
        fh.write(text)
    print("wrote %s (doors=2 probes=%d route=%d)" % (dst, 6, len(d["probes"]["e2e_route"])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
