#!/usr/bin/env python3
"""S8 Task 5: write app/src/ride_points.h from tools/re/s8/placements.json.

  python3 -I tools/re/s8/ride_points.py [placements.json] [ride_points.h]

Transcribes `speeds`, `root_z`, `rider_root_xz`, `root_fps`, `footfalls` and the two
doors (`door_shrine`, `door_plain`: boxes and arrival spawns) verbatim (ruling R2), so
the header is reproducible from the gate's output. Stdlib only.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", ".."))


def f(v):
    s = repr(float(v))
    return s + "f"


def short(name):
    for p in ("horse_a_uma_", "player_a_uma_"):
        if name.startswith(p):
            return name[len(p):]
    return name


def render(d):
    sp, ff = d["speeds"], d["footfalls"]
    fps = d["root_fps"]
    out = []
    w = out.append
    w("#pragma once")
    w("")
    w("// GENERATED by tools/re/s8/ride_points.py from tools/re/s8/placements.json — do not edit;")
    w("// re-run the generator. Ruling R2: transcribed verbatim, no provisional values.")
    w("//")
    w("// Provenance (placements.json keys):")
    w("//   `speeds` (source: %s) — the gait loops' mean root speed, m/s along +Z;" % sp["source"])
    w("//   `root_z` (data: tools/re/s8/root_z.py tables, parse2.decode_root of each `.anb`) —")
    w("//     Agro's 14 non-loop riding clips, cumulative metres along +Z from frame 0, per frame;")
    w("//   `rider_root_xz` (data, same reader) — Wander's five mount/dismount clips, [x, z] metres")
    w("//     per frame in Agro's frame relative to OptBone_boy (y comes from the clip itself);")
    w("//   `root_fps` (data, the `.anb` rate field) — each table's frame rate: frame = time * fps;")
    w("//   `footfalls` (source: %s) — touchdown fractions of the gait loops, design §6 values;" % ff["source"])
    w("//     `footfalls_remeasured` differs by one frame (trot FR 0.222, gallop BL 0.0).")
    w("// A clip's runtime duration is (frames - 1) / fps (the last key, as death.h's R8).")
    w("")
    w("namespace ride_points {")
    w("")
    w("inline constexpr float kSpeedWalk = %s;    // horse_a_uma_walk" % f(sp["walk"]))
    w("inline constexpr float kSpeedTrot = %s;    // horse_a_uma_run_n" % f(sp["trot"]))
    w("inline constexpr float kSpeedGallop = %s;  // horse_a_uma_run" % f(sp["gallop"]))
    w("inline constexpr float kSpeedBack = %s;    // horse_a_uma_back" % f(sp["back"]))
    w("")
    w("struct RootZ {")
    w("    const char* clip;")
    w("    float fps;")
    w("    int frames;")
    w("    const float* z;")
    w("};")
    w("")
    for name, z in d["root_z"].items():
        w("inline constexpr float kZ_%s[] = {%s};" % (short(name), ", ".join(f(v) for v in z)))
    w("")
    w("inline constexpr RootZ kRootZ[] = {")
    for name, z in d["root_z"].items():
        w('    {"%s", %s, %d, kZ_%s},' % (name, f(fps[name]), len(z), short(name)))
    w("};")
    w("")
    w("struct RiderXZ {")
    w("    const char* clip;")
    w("    float fps;")
    w("    int frames;")
    w("    const float (*xz)[2];")
    w("};")
    w("")
    for name, xz in d["rider_root_xz"].items():
        w("inline constexpr float kXZ_%s[][2] = {%s};" % (
            short(name), ", ".join("{%s, %s}" % (f(p[0]), f(p[1])) for p in xz)))
    w("")
    w("inline constexpr RiderXZ kRiderXZ[] = {")
    for name, xz in d["rider_root_xz"].items():
        w('    {"%s", %s, %d, kXZ_%s},' % (name, f(fps[name]), len(xz), short(name)))
    w("};")
    w("")
    w("// Ascending touchdown fractions of the loop (one per hoof; the hoof order differs per gait,")
    w("// design §6) — the footfall scheduler needs only the moments.")
    for g in ("walk", "trot", "gallop"):
        w("inline constexpr float kFootfall%s[4] = {%s};" % (
            g.capitalize(), ", ".join(f(v) for v in ff[g])))
    w("")
    ds, dp = d["door_shrine"], d["door_plain"]
    w("// The doors (design D14; source: %s): trigger boxes that fire on entry, each with" % ds["source"])
    w("// the arrival spawn on the other stage. `door_shrine` is in the shrine's frame and")
    w("// arrives on the plain (world frame); `door_plain` is in the world frame and arrives")
    w("// in the shrine's frame.")
    w("struct Door {")
    w("    float min[3], max[3];")
    w("    float arrive[3];")
    w("    float arriveYawDeg;")
    w("};")
    w("")
    for name, door, arrive in (("kDoorShrine", ds, ds["arrive_plain"]),
                               ("kDoorPlain", dp, dp["arrive_shrine"])):
        w("inline constexpr Door %s{{%s}, {%s}, {%s}, %s};" % (
            name, ", ".join(f(v) for v in door["min"]), ", ".join(f(v) for v in door["max"]),
            ", ".join(f(v) for v in arrive["p"]), f(arrive["yaw_deg"])))
    w("")
    w("}  // namespace ride_points")
    return "\n".join(out) + "\n"


def main(argv):
    src = argv[1] if len(argv) > 1 else os.path.join(HERE, "placements.json")
    dst = argv[2] if len(argv) > 2 else os.path.join(REPO, "app", "src", "ride_points.h")
    with open(src) as fh:
        d = json.load(fh)
    text = render(d)
    with open(dst, "w") as fh:
        fh.write(text)
    print("wrote %s (root_z=%d rider=%d)" % (dst, len(d["root_z"]), len(d["rider_root_xz"])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
